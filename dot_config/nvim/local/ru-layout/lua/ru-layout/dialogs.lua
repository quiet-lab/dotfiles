-- Ответы встроенных запросов в русской раскладке.
--
-- langmap не применяется к букве-ответу в запросах `confirm()` и подтверждения
-- `:s///c` (оба — режим `r?`): `н` вместо `y` не принимается. Обработчик vim.on_key
-- в этом режиме заменяет кириллицу клавишей той же физической клавиши в us:
-- исходная клавиша отбрасывается (возврат ""), перевод подаётся в начало очереди
-- ввода как набранный. `inputlist()` ждёт цифры, они одинаковы в обеих раскладках,
-- обёртка не нужна. Приглашение `-- More --` читает клавиши мимо vim.on_key и не
-- переводится (остаток, заметка задачи).
local tr = require("ru-layout.tr")

local M = {}

-- Режимы nvim_get_mode(), в которых ответ — одна буква латиницей.
M.modes = { ["r?"] = true }

local ns

-- Обработчик on_key: символы без пары (ASCII, клавиши) проходят без проверки режима.
function M.on_key(key)
  local us = tr.ru2us[key]
  if not us then
    return
  end
  if M.modes[vim.api.nvim_get_mode().mode] then
    vim.api.nvim_feedkeys(us, "int", false)
    return ""
  end
end

-- Повторный вызов заменяет обработчик в том же пространстве имён.
function M.setup()
  ns = vim.on_key(M.on_key, ns)
end

return M
